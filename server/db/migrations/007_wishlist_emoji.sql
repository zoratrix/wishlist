-- 007_wishlist_emoji.sql — необязательное эмодзи-оформление вишлиста.
--
-- theme_emoji TEXT NULL: NULL — «без эмодзи». Строка 1–8 UTF-16 символов,
-- содержащая минимум один эмодзи (Extended_Pictographic), без ASCII-букв,
-- цифр и пробелов. Проверяется сервисом, а не CHECK в БД: так невалидное
-- значение возвращает 400 INVALID_EMOJI, а список допустимых эмодзи можно
-- расширять без миграции. Существующие вишлисты автоматически получают NULL.

ALTER TABLE wishlists ADD COLUMN theme_emoji TEXT;
