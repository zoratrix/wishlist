-- 004_category_color.sql — необязательный цвет категории (тега).
--
-- color TEXT NULL: NULL означает «цвет по умолчанию» (нейтральный). Палитру
-- из 8 значений проверяет сервис (server/src/lib/schemas.ts), а не CHECK в БД:
-- так список допустимых цветов можно расширять без изменения схемы и миграции
-- на существующих базах. Column nullable, поэтому существующие категории
-- автоматически получают NULL и остаются валидными.

ALTER TABLE categories ADD COLUMN color TEXT;
